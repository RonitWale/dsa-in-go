first_variable = int(input("Enter the first variable : "))
second_variable = int(input("Enter the second variable: "))
# Addition
print(first_variable + second_variable)

# substraction
print(first_variable - second_variable)

# multiplication
print(first_variable * second_variable)

# division
print(first_variable / second_variable)

# floor division
print(first_variable // second_variable)

# exponential
print(first_variable ** second_variable)

# modulo
print(first_variable % second_variable)


# greater than 
print(first_variable > second_variable)

# lesser than
print(first_variable < second_variable)

#equals to
print(first_variable == second_variable)

# not equals to
print(first_variable != second_variable)

# greater than equal
print(first_variable >= second_variable)

#lesser than equal
print(first_variable <= second_variable)

#and 
print((first_variable + 1) > (second_variable - 1) and (first_variable - 1) > (second_variable + 1))
#and 
print((first_variable + 1) > (second_variable - 1) or (first_variable - 1) > (second_variable + 1))
#not
print(not((first_variable + 1) > (second_variable - 1) and (first_variable - 1) > (second_variable + 1)))